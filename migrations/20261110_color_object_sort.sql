-- Add a database-backed object-to-color sorting activity for module 3 (Cores).
-- Apply this migration before deploying the backend that reads these tables.
begin;

create table if not exists public.variacao_grupos (
  id bigint generated by default as identity primary key,
  variacao_id integer not null
    references public.variacoes_atividades(id) on delete cascade,
  chave varchar(40) not null,
  palavra_en varchar(40) not null,
  palavra_pt varchar(60) not null,
  ordem smallint not null check (ordem > 0),
  constraint variacao_grupos_chave_unique unique (variacao_id, chave),
  constraint variacao_grupos_ordem_unique unique (variacao_id, ordem)
);

create table if not exists public.variacao_cartoes (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null
    references public.variacao_grupos(id) on delete cascade,
  palavra_en varchar(60) not null,
  palavra_pt varchar(60) not null,
  url_imagem text not null,
  ordem smallint not null check (ordem > 0),
  constraint variacao_cartoes_ordem_unique unique (grupo_id, ordem)
);

create index if not exists variacao_grupos_variacao_idx
  on public.variacao_grupos (variacao_id, ordem);
create index if not exists variacao_cartoes_grupo_idx
  on public.variacao_cartoes (grupo_id, ordem);

alter table public.variacao_grupos enable row level security;
alter table public.variacao_cartoes enable row level security;

revoke all on public.variacao_grupos from anon, authenticated;
revoke all on public.variacao_cartoes from anon, authenticated;
grant select on public.variacao_grupos to anon, authenticated;
grant select on public.variacao_cartoes to anon, authenticated;
grant select on public.variacao_grupos to service_role;
grant select on public.variacao_cartoes to service_role;

drop policy if exists "Read activity category groups"
  on public.variacao_grupos;
create policy "Read activity category groups"
  on public.variacao_grupos for select to anon, authenticated
  using (true);

drop policy if exists "Read activity category cards"
  on public.variacao_cartoes;
create policy "Read activity category cards"
  on public.variacao_cartoes for select to anon, authenticated
  using (true);

do $$
declare
  v_activity_id integer;
  v_variation_id integer;
  v_group_id bigint;
  v_seed record;
begin
  select id
    into v_activity_id
    from public.atividades
   where modulo_id = 3 and ordem_sequencia = 13
   limit 1;

  if v_activity_id is null then
    insert into public.atividades (modulo_id, palavra_chave, ordem_sequencia)
    values (3, 'RED', 13)
    returning id into v_activity_id;
  end if;

  select id
    into v_variation_id
    from public.variacoes_atividades
   where atividade_id = v_activity_id
     and modo_alvo = 'Nível 1 - Suporte Visual Puro'
     and tipo_interacao = 'SepararPorCor'
   limit 1;

  if v_variation_id is null then
    if exists (
      select 1 from public.variacoes_atividades
       where atividade_id = v_activity_id
         and modo_alvo = 'Nível 1 - Suporte Visual Puro'
    ) then
      raise exception
        'A etapa 13 já possui uma variação de nível 1 com outro tipo de interação.';
    end if;

    insert into public.variacoes_atividades (
      atividade_id, modo_alvo, instrucao_lex,
      url_midia_padrao, tipo_interacao, resposta_correta
    ) values (
      v_activity_id,
      'Nível 1 - Suporte Visual Puro',
      'Observe o objeto e arraste-o até o grupo da cor correspondente.',
      null,
      'SepararPorCor',
      'RED'
    )
    returning id into v_variation_id;
  end if;

  if not exists (
    select 1 from public.variacao_grupos
     where variacao_id = v_variation_id
  ) then
    for v_seed in
      select * from (values
        ('color-red',    'RED',    'Vermelho', 1, 'APPLE',  'Maçã',    '/public/assets/imagens/modulos/cores-formas/objetos/red-apple.svg'),
        ('color-blue',   'BLUE',   'Azul',     2, 'FISH',   'Peixe',   '/public/assets/imagens/modulos/cores-formas/objetos/blue-fish.svg'),
        ('color-yellow', 'YELLOW', 'Amarelo',  3, 'BANANA', 'Banana',  '/public/assets/imagens/modulos/cores-formas/objetos/yellow-banana.svg'),
        ('color-green',  'GREEN',  'Verde',    4, 'LEAF',   'Folha',   '/public/assets/imagens/modulos/cores-formas/objetos/green-leaf.svg'),
        ('color-orange', 'ORANGE', 'Laranja',  5, 'ORANGE', 'Laranja', '/public/assets/imagens/modulos/cores-formas/objetos/orange-fruit.svg'),
        ('color-purple', 'PURPLE', 'Roxo',     6, 'GRAPES', 'Uvas',    '/public/assets/imagens/modulos/cores-formas/objetos/purple-grapes.svg')
      ) as seed(chave, cor_en, cor_pt, ordem_grupo,
                objeto_en, objeto_pt, url_imagem)
    loop
      insert into public.variacao_grupos (
        variacao_id, chave, palavra_en, palavra_pt, ordem
      ) values (
        v_variation_id, v_seed.chave, v_seed.cor_en,
        v_seed.cor_pt, v_seed.ordem_grupo
      ) returning id into v_group_id;

      insert into public.variacao_cartoes (
        grupo_id, palavra_en, palavra_pt, url_imagem, ordem
      ) values (
        v_group_id, v_seed.objeto_en, v_seed.objeto_pt,
        v_seed.url_imagem, 1
      );
    end loop;
  end if;
end;
$$;

commit;
